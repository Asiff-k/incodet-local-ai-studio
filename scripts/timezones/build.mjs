// Builds src/content/timezones.ts: IANA time zone -> ISO country code, from the tz database.
// Run: node scripts/timezones/build.mjs   (needs internet; no dependencies)
// Sources: zone.tab (one country per zone) and backward (old names such as Asia/Calcutta).
import fs from "node:fs";
import path from "node:path";

const base = "https://raw.githubusercontent.com/eggert/tz/main/";
const [zoneTab, backward] = await Promise.all(
  ["zone.tab", "backward"].map(async (f) => {
    const res = await fetch(base + f);
    if (!res.ok) throw new Error(`Could not download ${f}: ${res.status}`);
    return res.text();
  }),
);

const country = {};
for (const line of zoneTab.split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , zone] = line.split("\t");
  if (cc && zone) country[zone] = cc;
}

// "Link  TARGET  ALIAS": give old names the country of the zone they point to.
let aliases = 0;
const current = {};
for (const line of backward.split("\n")) {
  const parts = line.split(/\s+/);
  if (parts[0] !== "Link") continue;
  const [, target, alias] = parts;
  if (!alias || !alias.includes("/") || alias.startsWith("Etc/")) continue;
  if (country[target] && !country[alias]) {
    country[alias] = country[target];
    current[alias] = target;
    aliases++;
  }
}

const entries = Object.keys(country)
  .sort()
  .map((z) => `  "${z}": "${country[z]}",`)
  .join("\n");
const currentEntries = Object.keys(current)
  .sort()
  .map((z) => `  "${z}": "${current[z]}",`)
  .join("\n");
const out = `// Generated by scripts/timezones/build.mjs from the tz database (zone.tab + backward).
// Do not edit by hand: run the script again to update.

/** IANA time zone (including old names browsers may report) to ISO 3166 country code. */
export const zoneCountry: Record<string, string> = {
${entries}
};

/** Old zone names (still reported by some browsers) to their current tz database name. */
export const zoneCurrent: Record<string, string> = {
${currentEntries}
};
`;
const file = path.resolve("src/content/timezones.ts");
fs.writeFileSync(file, out);
console.log(`Wrote ${Object.keys(country).length} zones (${aliases} old names) to ${file}`);
